from __future__ import annotations

import argparse
import json
import math
import socket
from pathlib import Path

import numpy as np
from stable_baselines3 import SAC

from mars_rover.envs import RoverEnv


def wrap_pi(angle: float) -> float:
    return (angle + math.pi) % (2.0 * math.pi) - math.pi


class ExactUnityObservationAdapter:
    """
    Build the SAME SAC observation contract used by RoverEnv:
      terrain: uint8 (5, 32, 32)
      state:   float32 (14,)

    The static terrain channels are generated by RoverEnv._sample_local_map()
    itself, so elevation/slope/roughness/known-obstacle normalization is not
    duplicated or approximated here.

    Unity LiDAR is fused only into channel 3 (obstacle occupancy).
    Standalone SAC channel 4 (route) remains zero, exactly as during training.
    """

    def __init__(
        self,
        model: SAC,
        terrain_npz: str,
        unity_origin_x: float = 0.0,
        unity_origin_z: float = 0.0,
        flip_unity_x: bool = False,
        flip_unity_z: bool = False,
    ):
        self.model = model
        self.terrain_npz = str(Path(terrain_npz).resolve())
        self.unity_origin_x = float(unity_origin_x)
        self.unity_origin_z = float(unity_origin_z)
        self.flip_unity_x = bool(flip_unity_x)
        self.flip_unity_z = bool(flip_unity_z)

        # Use RoverEnv itself as the authoritative terrain-observation builder.
        self.helper = RoverEnv(
            [self.terrain_npz],
            action_mode="continuous",
            route_observation=False,
            render_mode=None,
            local_map_size=32,
            local_span_m=24.0,
            randomize_physics=False,
            fixed_terrain=self.terrain_npz,
            sensor_preview=False,
            curriculum_enabled=False,
        )
        self.helper._load_random_terrain()

        self.rows, self.cols = self.helper.height.shape
        self.res = float(self.helper.res)
        self.half_x = 0.5 * (self.cols - 1) * self.res
        self.half_y = 0.5 * (self.rows - 1) * self.res
        self.width_m = (self.cols - 1) * self.res
        self.depth_m = (self.rows - 1) * self.res
        self.diag = max(1.0, math.hypot(self.rows, self.cols) * self.res)

        self.prev_action = np.zeros(2, dtype=np.float32)
        self.battery = 1.0
        self.have_previous_action = False

        expected = self.model.observation_space
        if not hasattr(expected, "spaces"):
            raise RuntimeError(f"Expected Dict observation space, got {expected!r}")

        terrain_shape = tuple(expected.spaces["terrain"].shape)
        state_shape = tuple(expected.spaces["state"].shape)
        if terrain_shape != (5, 32, 32) or state_shape != (14,):
            raise RuntimeError(
                f"Unexpected model observation shapes: terrain={terrain_shape}, state={state_shape}"
            )

        print("[exact] terrain:", self.terrain_npz)
        print(f"[exact] source grid: {self.rows} x {self.cols}, res={self.res:.6f} m/cell")
        print(f"[exact] physical size expected in Unity: X={self.width_m:.3f} m, Z={self.depth_m:.3f} m")
        print(f"[exact] model diag normalization: {self.diag:.3f} m")
        print("[exact] local map: 32 x 32 over 24.0 m")
        print("[exact] standalone SAC route channel/state = zero")

    def close(self):
        try:
            self.helper.close()
        except Exception:
            pass

    def _unity_axis_to_pb(self, ux: float, uz: float) -> tuple[float, float]:
        # Unity Terrain occupies [origin, origin+size].
        lx = float(ux) - self.unity_origin_x
        lz = float(uz) - self.unity_origin_z

        if self.flip_unity_x:
            lx = self.width_m - lx
        if self.flip_unity_z:
            lz = self.depth_m - lz

        # PyBullet terrain is centered at (0, 0).
        return lx - self.half_x, lz - self.half_y

    def _unity_forward_to_pb_yaw(self, fx: float, fz: float) -> float:
        # Apply the same optional terrain-axis flips to a direction vector.
        if self.flip_unity_x:
            fx = -fx
        if self.flip_unity_z:
            fz = -fz

        norm = math.hypot(fx, fz)
        if norm < 1e-8:
            return 0.0

        fx /= norm
        fz /= norm

        # PyBullet forward basis is [cos(yaw), sin(yaw)] in X/Y.
        return math.atan2(fz, fx)

    def advance_previous_action_state(self):
        """
        RoverEnv updates battery during step(action_t), then obs_{t+1} contains:
          battery after action_t
          prev_action = action_t

        Each Unity packet arrives after the previously returned action has been
        applied for one policy interval, so update battery here before building
        the next observation.
        """
        if not self.have_previous_action:
            return

        steer = float(self.prev_action[0])
        throttle = float(self.prev_action[1])

        # Exact randomize_physics=False RoverEnv max speed is 0.95 m/s.
        command_effort = abs(throttle) * 0.95 + 0.30 * abs(steer)
        self.battery = max(0.0, self.battery - 0.00065 * command_effort)

    def build(self, p: dict) -> tuple[dict[str, np.ndarray], dict]:
        self.advance_previous_action_state()

        ux, _, uz = map(float, p["position"])
        pb_x, pb_y = self._unity_axis_to_pb(ux, uz)

        forward_xz = p.get("forward_xz", [0.0, 1.0])
        yaw_pb = self._unity_forward_to_pb_yaw(
            float(forward_xz[0]), float(forward_xz[1])
        )

        # Exact static 5-channel map from the current RoverEnv implementation.
        terrain = self.helper._sample_local_map(
            np.array([pb_x, pb_y, 0.0], dtype=np.float64),
            yaw_pb,
        ).copy()

        # Fuse Unity LiDAR into the existing obstacle channel only.
        lidar = np.asarray(p["occupancy_32x32"], dtype=np.float32)
        if lidar.size != 32 * 32:
            raise RuntimeError(f"Unity LiDAR grid has {lidar.size} cells, expected 1024")
        lidar = lidar.reshape(32, 32)
        lidar_u8 = np.where(lidar > 0.5, 255, 0).astype(np.uint8)
        terrain[3] = np.maximum(terrain[3], lidar_u8)

        # Goal direction is computed in the rover's LOCAL Unity frame to avoid
        # handedness/yaw-convention ambiguity.
        goal_local = p.get("goal_local_xz")
        if goal_local is not None and len(goal_local) >= 2:
            goal_right = float(goal_local[0])   # Unity +X = rover-right
            goal_forward = float(goal_local[1]) # Unity +Z = rover-forward
            goal_dist = math.hypot(goal_right, goal_forward)
            rel_goal = math.atan2(-goal_right, goal_forward)  # + = rover-left
        else:
            gx, gz = map(float, p["goal_xz"])
            goal_dist = math.hypot(gx - ux, gz - uz)
            # Fallback: derive via world vectors.
            fx, fz = map(float, forward_xz)
            norm_f = max(1e-8, math.hypot(fx, fz))
            fx, fz = fx / norm_f, fz / norm_f
            rx, rz = fz, -fx  # rover-right in Unity XZ
            dx, dz = gx - ux, gz - uz
            goal_forward = dx * fx + dz * fz
            goal_right = dx * rx + dz * rz
            rel_goal = math.atan2(-goal_right, goal_forward)

        local_v = p["local_velocity"]
        v_lateral = -float(local_v[0])  # Unity +X is right; model wants +left
        v_forward = float(local_v[2])   # Unity +Z is forward

        yaw_rate = float(p.get("yaw_rate_rad_s", 0.0))  # packet already left-positive
        roll = math.radians(float(p.get("roll_deg", 0.0)))
        pitch = math.radians(float(p.get("pitch_deg", 0.0)))
        slip = float(np.clip(float(p.get("slip", 0.0)), 0.0, 1.0))

        state = np.array(
            [
                np.clip(goal_dist / self.diag, 0.0, 1.0),
                math.sin(rel_goal),
                math.cos(rel_goal),
                np.clip(v_forward / 1.3, -1.0, 1.0),
                np.clip(v_lateral / 1.0, -1.0, 1.0),
                np.clip(yaw_rate / 2.0, -1.0, 1.0),
                np.clip(roll / math.radians(50.0), -1.0, 1.0),
                np.clip(pitch / math.radians(50.0), -1.0, 1.0),
                slip,
                np.clip(self.battery, 0.0, 1.0),
                float(self.prev_action[0]),
                float(self.prev_action[1]),
                0.0,  # standalone SAC path_dist
                0.0,  # standalone SAC path_heading_sin
            ],
            dtype=np.float32,
        )

        obs = {
            "terrain": terrain.astype(np.uint8, copy=False),
            "state": state,
        }

        debug = {
            "pb_x": pb_x,
            "pb_y": pb_y,
            "yaw_pb_deg": math.degrees(yaw_pb),
            "goal_dist": goal_dist,
            "rel_goal_deg": math.degrees(rel_goal),
            "v_forward": v_forward,
            "v_lateral": v_lateral,
            "slip": slip,
            "battery": self.battery,
            "lidar_cells": int(np.count_nonzero(lidar_u8)),
            "obstacle_cells_total": int(np.count_nonzero(terrain[3])),
        }
        return obs, debug

    def record_returned_action(self, action: np.ndarray):
        self.prev_action[:] = np.asarray(action, dtype=np.float32).reshape(2)
        self.have_previous_action = True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, help="500k SAC .zip")
    ap.add_argument(
        "--terrain-npz",
        required=True,
        help="EXACT .npz terrain tile from which the Unity heightmap was exported",
    )
    ap.add_argument("--listen-port", type=int, default=5005)
    ap.add_argument("--unity-port", type=int, default=5006)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--unity-origin-x", type=float, default=0.0)
    ap.add_argument("--unity-origin-z", type=float, default=0.0)
    ap.add_argument("--flip-unity-x", action="store_true")
    ap.add_argument("--flip-unity-z", action="store_true")
    ap.add_argument("--debug-every", type=int, default=25)
    args = ap.parse_args()

    print("[bridge] loading SAC:", args.model)
    model = SAC.load(args.model, device=args.device)
    adapter = ExactUnityObservationAdapter(
        model=model,
        terrain_npz=args.terrain_npz,
        unity_origin_x=args.unity_origin_x,
        unity_origin_z=args.unity_origin_z,
        flip_unity_x=args.flip_unity_x,
        flip_unity_z=args.flip_unity_z,
    )

    rx = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    rx.bind(("127.0.0.1", args.listen_port))
    tx = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)

    print(f"[bridge] listening on 127.0.0.1:{args.listen_port}")
    print(f"[bridge] sending to 127.0.0.1:{args.unity_port}")
    print("[bridge] CTRL+C to stop")

    count = 0
    try:
        while True:
            data, _ = rx.recvfrom(65535)
            p = {}
            try:
                p = json.loads(data.decode("utf-8"))
                obs, dbg = adapter.build(p)

                action, _ = model.predict(obs, deterministic=True)
                a = np.asarray(action, dtype=np.float32).reshape(2)

                if not np.isfinite(a).all():
                    raise RuntimeError(f"Non-finite action: {a}")

                a = np.clip(a, -1.0, 1.0)
                adapter.record_returned_action(a)

                reply = {
                    "seq": int(p["seq"]),
                    "steer": float(a[0]),
                    "throttle": float(a[1]),
                    "ok": True,
                    "message": "ok",
                }

                count += 1
                if args.debug_every > 0 and (count == 1 or count % args.debug_every == 0):
                    s = obs["state"]
                    print(
                        f"[{count:05d}] seq={int(p['seq'])} "
                        f"pb=({dbg['pb_x']:+.2f},{dbg['pb_y']:+.2f}) "
                        f"yaw={dbg['yaw_pb_deg']:+.1f}deg "
                        f"goal={dbg['goal_dist']:.1f}m rel={dbg['rel_goal_deg']:+.1f}deg "
                        f"vF={dbg['v_forward']:+.2f} vL={dbg['v_lateral']:+.2f} "
                        f"slip={dbg['slip']:.2f} lidar={dbg['lidar_cells']} "
                        f"state0={s[0]:.3f} sin/cos=({s[1]:+.3f},{s[2]:+.3f}) "
                        f"action=({a[0]:+.3f},{a[1]:+.3f})"
                    )

            except Exception as e:
                reply = {
                    "seq": int(p.get("seq", 0)) if isinstance(p, dict) else 0,
                    "steer": 0.0,
                    "throttle": 0.0,
                    "ok": False,
                    "message": repr(e),
                }
                print("[bridge] ERROR:", reply["message"])

            tx.sendto(
                json.dumps(reply).encode("utf-8"),
                ("127.0.0.1", args.unity_port),
            )

    except KeyboardInterrupt:
        print("\n[bridge] stopped")
    finally:
        adapter.close()
        rx.close()
        tx.close()


if __name__ == "__main__":
    main()
